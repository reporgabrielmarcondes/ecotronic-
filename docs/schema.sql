-- As tabelas são criadas AUTOMATICAMENTE pelo Hibernate
-- (spring.jpa.hibernate.ddl-auto=update). Este arquivo existe para
-- documentação/relatório e para quem preferir criar o banco na mão.

CREATE TABLE perfis (
    id         UUID         PRIMARY KEY,           -- mesmo id do usuário no Supabase Auth
    nome       VARCHAR(100) NOT NULL,
    email      VARCHAR(255),
    token      VARCHAR(6)   NOT NULL UNIQUE,       -- código digitado no totem
    is_admin   BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em  TIMESTAMP    NOT NULL
);

CREATE TABLE descartes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    totem_id        VARCHAR(50)  NOT NULL,
    categoria       VARCHAR(30)  NOT NULL,
    categoria_nome  VARCHAR(100) NOT NULL,
    ecodots         INTEGER      NOT NULL,
    criado_em       TIMESTAMP    NOT NULL,
    usuario_id      UUID         REFERENCES perfis (id)   -- NULL = descarte sem identificação
);

CREATE INDEX idx_descartes_criado_em ON descartes (criado_em);
CREATE INDEX idx_descartes_usuario   ON descartes (usuario_id);

